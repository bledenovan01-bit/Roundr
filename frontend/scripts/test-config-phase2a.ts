import { lovableConfigTeams, lovableLaunchDefaults, lovableReplayConfig, mergeConfigurationTeams } from "../src/features/lovable-config-state";
import { defaultConfig, defaultTeams } from "../src/domain/defaults";
import { advance, cancelNextLaunch, correctLast, createSession, endManual, endSession, launchNext, pauseNextLaunch, resumeNextLaunch, startNextImmediately, startNextPeriod } from "../src/domain/session";
import { elapsedMs } from "../src/chrono/engine";
import { validSession } from "../src/store/storage-validation";
import { validateConfig } from "../src/domain/validate";
import type { MaracanaConfig } from "../src/domain/types";
const assert = (process as unknown as { getBuiltinModule: (id: string) => any }).getBuiltinModule("assert/strict");

const c = lovableLaunchDefaults("classique");
assert.equal(c.mode, "classique");
if (c.mode !== "classique") throw Error();
assert.equal(c.totalMin, 30); assert.equal(c.periods, 2); assert.equal(c.breakMin, 5); assert.equal(c.additional, false);
const classic = createSession(c, lovableConfigTeams("classique", 2), 1000);
assert.deepEqual(classic.live!.periodMs, [900000,900000]);
assert.deepEqual(lovableConfigTeams("classique",2).map(team=>team.name),["Les Renards","FC Amigos"]);
assert.deepEqual((defaultConfig("classique") as typeof c).totalMin, 10, "legacy defaults remain available");
console.log("✓ New classic defaults match Lovable; legacy defaults and engine remain intact");
const oldClassic=defaultConfig("classique") as typeof c, frozenReplay=JSON.stringify(oldClassic);
assert.equal((lovableReplayConfig(oldClassic) as typeof c).additionalEachPeriod,true); assert.equal(JSON.stringify(oldClassic),frozenReplay);
assert.equal((lovableReplayConfig(oldClassic) as typeof c).totalMin,oldClassic.totalMin);
let halves=createSession({...c,totalMin:2,breakMin:1,additional:true},lovableConfigTeams("classique",2),1000);
halves=advance(halves,61000); assert.equal(halves.live!.stage,"additional");
halves=endManual(halves,71000); assert.equal(halves.live!.stage,"break"); assert.equal(halves.live!.playedMs,70000);
halves=advance(halves,131000); assert.equal(halves.live!.stage,"awaitPeriod");
halves=startNextPeriod(halves,131000); halves=advance(halves,191000); assert.equal(halves.live!.stage,"additional");
halves=endManual(halves,196000); assert.equal(halves.live!.stage,"finished"); assert.equal(halves.matches[0].playedMs,135000);
assert.equal(validSession(JSON.parse(JSON.stringify(halves))),true);
console.log("✓ Additional time applies to both new classic halves, excludes the break, and restores unchanged");
const base = lovableLaunchDefaults("maracana") as MaracanaConfig;
assert.equal(base.teamCount,5); assert.equal(base.customTeams,true); assert.equal(base.launch,"manual");
assert.deepEqual(lovableConfigTeams("maracana",3).map(t=>t.name),["Les Renards","FC Amigos","Panthères"]);
const previous=lovableConfigTeams("maracana",8), imported=[previous[7],previous[6],previous[5]].map(t=>({...t,name:"Import "+t.name}));
const beforeMerge=JSON.stringify(previous), merged=mergeConfigurationTeams(previous,imported);
assert.equal(new Set(merged.map(t=>t.id)).size,8); assert.deepEqual(merged.slice(0,3),imported);
assert.deepEqual(merged.slice(3).map(t=>[t.name,t.color]),previous.slice(3).map(t=>[t.name,t.color]));
assert.equal(JSON.stringify(previous),beforeMerge);
assert.equal(validateConfig({...base,teamCount:8},merged).length,0);
console.log("✓ Reordered imports and hidden team edits survive resizing with unique IDs");
function finished(launch: "manual"|"auto"|"delay", n=5) {
  const config:MaracanaConfig={...base,teamCount:n,launch,launchDelaySec:30,end:{byTime:true,goalTarget:null}};
  const s=createSession(config,lovableConfigTeams("maracana",n),1000);
  return endManual(s,11000);
}
const manual=advance(finished("manual"),11000);
assert.equal(manual.live!.stage,"finished"); assert.equal(manual.pendingLaunch,undefined);
assert.equal(launchNext(manual,12000).live!.stage,"ready");
console.log("✓ Manual launch stays ready until the organizer starts it");
const auto=advance(finished("auto"),11000);
assert.equal(auto.live!.matchId,"m2"); assert.equal(auto.live!.chrono.runningSince,11000);
assert.equal(advance(auto,11000),auto); assert.equal(auto.matches.filter(m=>m.status==="finished").length,1);
console.log("✓ Automatic launch starts exactly one next match");
const pending=advance(finished("delay"),11000);
assert.ok(pending.pendingLaunch); assert.equal(pending.live!.matchId,"m1");
assert.equal(advance(pending,40999).live!.matchId,"m1");
const launched=advance(pending,45000);
assert.equal(launched.live!.matchId,"m2"); assert.equal(launched.live!.chrono.runningSince,41000);
assert.equal(elapsedMs(launched.live!.chrono,45000),4000);
assert.equal(launched.pendingLaunch,undefined); assert.equal(advance(launched,45000),launched);
console.log("✓ Delay uses timestamps and resumes at its exact boundary, without duplicate results");
assert.equal(validSession(pending),true);
const restored=JSON.parse(JSON.stringify(pending));
assert.equal(advance(restored,45000).live!.chrono.runningSince,41000);
assert.equal(validSession({...pending,pendingLaunch:{...pending.pendingLaunch,chrono:{...pending.pendingLaunch!.chrono,runningSince:NaN}}}),false);
assert.equal(validSession({...pending,pendingLaunch:{...pending.pendingLaunch,key:"wrong-match"}}),false);
console.log("✓ Pending launch round-trips through storage; invalid or stale clocks are rejected");
const paused=pauseNextLaunch(pending,16000);
assert.equal(paused.pendingLaunch!.chrono.runningSince,null);
assert.equal(advance(paused,100000).live!.matchId,"m1");
const resumed=resumeNextLaunch(paused,100000);
assert.equal(advance(resumed,124999).live!.matchId,"m1");
assert.equal(advance(resumed,125000).live!.matchId,"m2");
const cancelled=cancelNextLaunch(pending,16000);
assert.equal(advance(cancelled,100000).live!.matchId,"m1");
assert.equal(startNextImmediately(cancelled,100000).live!.chrono.runningSince,100000);
assert.equal(advance(endSession(pending,16000),100000).status,"finished");
console.log("✓ Delay pause/resume/cancel/immediate launch and ending a session are effective");
const corrected=correctLast(pending,0,1,16000);
assert.equal(advance(corrected,100000).live!.matchId,"m1","score correction cancels the pending automatic launch");
assert.equal(corrected.matches.filter(m=>m.status==="finished").length,1);
console.log("✓ Score correction cannot trigger an obsolete automatic launch");
// Frozen reference FIFO: next waiting teams enter; the previous winner queues first.
const f=finished("manual");
assert.deepEqual(f.maracana!.onField,["t3","t4"]); assert.deepEqual(f.maracana!.waiting,["t5","t1","t2"]);
const winB=correctLast(f,1,1,12000);
assert.deepEqual(winB.maracana!.waiting,["t5","t2","t1"]);
for (const n of [3,4,5,8]) for (const drawRule4 of ["oneLeaves","bothLeave"] as const) {
  const config={...base,teamCount:n,rotation:"winnerStays" as const,drawRule4,end:{byTime:false,goalTarget:3}};
  const done=endManual(createSession(config,lovableConfigTeams("maracana",n),1000),11000);
  assert.deepEqual(done.maracana!.onField,n>=4&&drawRule4==="bothLeave"?["t3","t4"]:["t2","t3"]);
}
const legacy=createSession(defaultConfig("maracana"),defaultTeams("maracana",3),1000);
assert.equal(validSession(legacy),true); assert.equal(advance(endManual(legacy,11000),200000).live!.stage,"finished");
console.log("✓ FIFO, winner-stays and both draw rules match the reference; old sessions stay manual");
for(const patch of [{launch:"invalid"},{rotation:"invalid"},{drawRule4:"invalid"},{launchDelaySec:Infinity},{launchDelaySec:0},{launchDelaySec:3601}]) {
  assert.ok(validateConfig({...base,...patch} as MaracanaConfig,lovableConfigTeams("maracana",5)).length);
}
console.log("✓ Invalid policies and non-finite/out-of-range delays cannot launch");
console.log("Phase 2A configuration and launch scenarios passed");
